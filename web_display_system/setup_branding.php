<script>
function livePreview() {
    var nav    = document.getElementById('preview-nav');
    var brand  = document.getElementById('preview-brand');
    var accent = document.getElementById('preview-accent-btn');
    nav.style.background    = document.getElementById('c_nav_bg').value;
    nav.style.borderBottom  = '1px solid ' + document.getElementById('c_nav_border').value;
    brand.style.color       = document.getElementById('c_nav_text').value;
    accent.style.background = document.getElementById('c_accent').value;
}

function previewLogo(input) {
    var wrap = document.getElementById('preview-logo-wrap');
    if (!input.files || !input.files[0]) return;
    var reader = new FileReader();
    reader.onload = function(e) {
        var img = document.getElementById('preview-logo-img');
        if (!img) {
            img = document.createElement('img');
            img.id = 'preview-logo-img';
            img.style.cssText = 'max-height:28px;max-width:100px;object-fit:contain;';
            img.alt = '';
            wrap.appendChild(img);
        }
        img.src = e.target.result;
    };
    reader.readAsDataURL(input.files[0]);
}
