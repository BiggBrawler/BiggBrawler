// ── Handle form submission ──────────────────────────────────
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['save_branding'])) {

    $navBg     = preg_match('/^#[0-9a-fA-F]{6}$/', $_POST['nav_bg']     ?? '') ? $_POST['nav_bg']     : '#1a252f';
    $navBorder = preg_match('/^#[0-9a-fA-F]{6}$/', $_POST['nav_border'] ?? '') ? $_POST['nav_border'] : '#0d1b24';
    $accent    = preg_match('/^#[0-9a-fA-F]{6}$/', $_POST['accent']     ?? '') ? $_POST['accent']     : '#3498db';
    $navText   = preg_match('/^#[0-9a-fA-F]{6}$/', $_POST['nav_text']   ?? '') ? $_POST['nav_text']   : '#ffffff';

    // Determine logo path — keep existing if no new file; validate to prevent path traversal
    $rawExisting = $_POST['existing_logo'] ?? '';
    $logoPath = (preg_match('/^uploads\/brand_logo\.[a-z]{2,4}$/', $rawExisting)) ? $rawExisting : '';

    if (!empty($_FILES['logo_file']['name'])) {
        $allowed = ['image/png','image/jpeg','image/gif','image/webp','image/svg+xml'];
        $ext_map = ['image/png'=>'png','image/jpeg'=>'jpg','image/gif'=>'gif',
                    'image/webp'=>'webp','image/svg+xml'=>'svg'];
        $mime = mime_content_type($_FILES['logo_file']['tmp_name']);
        if (!in_array($mime, $allowed, true)) {
            $message = 'Logo must be PNG, JPG, GIF, WEBP, or SVG.';
            $msgType = 'error';
        } else {
            $ext      = $ext_map[$mime];
            $destPath = 'uploads/brand_logo.' . $ext;
            $destFull = __DIR__ . '/' . $destPath;
            if (!move_uploaded_file($_FILES['logo_file']['tmp_name'], $destFull)) {
                $message = 'Could not save logo file. Check uploads/ folder permissions.';
                $msgType = 'error';
            } else {
                $logoPath = $destPath;
            }
        }
    }

    if ($message === '') {
        $lines  = "<?php\n";
        $lines .= "// ============================================================\n";
        $lines .= "// Store Branding Configuration\n";
        $lines .= "// Auto-generated by setup_branding.php — edit this file\n";
        $lines .= "// directly to update branding after initial setup.\n";
        $lines .= "// ============================================================\n";
        $lines .= "define('BRAND_LOGO',       " . var_export($logoPath, true) . ");\n";
        $lines .= "define('BRAND_NAV_BG',     " . var_export($navBg,    true) . ");\n";
        $lines .= "define('BRAND_NAV_BORDER', " . var_export($navBorder,true) . ");\n";
        $lines .= "define('BRAND_ACCENT',     " . var_export($accent,   true) . ");\n";
        $lines .= "define('BRAND_TEXT',       " . var_export($navText,  true) . ");\n";

        if (file_put_contents($configFile, $lines) === false) {
            $message = 'Could not write branding_config.php. Check file permissions.';
            $msgType = 'error';
        } else {
            $message = 'Branding saved. The builder will now display your store colors and logo.';
            $msgType = 'success';
        }
    }
}

